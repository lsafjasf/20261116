import { writeFile } from 'node:fs/promises';
import { AssemblyEngine } from '../src/engine.js';

const SEED = 0x7a11ce;
const MAX_TICKS = 5000;

function recordRun(policy, meta) {
  const engine = new AssemblyEngine({ seed: SEED });
  const events = [];
  let previousPhase = engine.state.phase;

  for (let guard = 0; guard < MAX_TICKS; guard += 1) {
    const state = engine.state;
    if (state.phase === 'active') {
      const actions = policy(engine, state);
      for (const action of actions) {
        if (action === 'left-press' && !state.leftHeld) {
          engine.press('left');
          events.push({ tick: engine.state.tick, kind: 'press', side: 'left' });
        } else if (action === 'left-release' && state.leftHeld) {
          engine.release('left');
          events.push({ tick: engine.state.tick, kind: 'release', side: 'left' });
        } else if (action === 'right-press' && !state.rightHeld) {
          engine.press('right');
          events.push({ tick: engine.state.tick, kind: 'press', side: 'right' });
        } else if (action === 'right-release' && state.rightHeld) {
          engine.release('right');
          events.push({ tick: engine.state.tick, kind: 'release', side: 'right' });
        }
      }
    }

    engine.tick();
    if (
      engine.state.phase === 'complete' ||
      engine.state.phase === 'failed'
    ) {
      break;
    }
    previousPhase = engine.state.phase;
  }

  const state = engine.state;
  return {
    id: meta.id,
    title: meta.title,
    summary: meta.summary,
    seed: SEED,
    startTick: 0,
    endTick: state.tick,
    durationMs: state.tick * 16,
    events,
    expected: {
      phase: state.phase,
      completed: state.completed,
      inventory: state.inventory,
      durability: state.durability,
      fingerprint: engine.fingerprint()
    },
    recordedTimeline: {
      conflicts: state.timeline.conflicts.map((item) => ({
        tick: item.tick,
        key: item.key,
        message: item.message,
        object: item.object,
        position: item.position
      })),
      collisions: state.timeline.collisions.map((item) => ({
        tick: item.tick,
        type: item.type,
        object: item.object,
        position: item.position
      })),
      results: state.timeline.results.map((item) => ({
        tick: item.tick,
        kind: item.kind,
        completed: item.completed,
        inventory: item.inventory
      }))
    }
  };
}

function safePulse(engine, state, preferRightFirst = false) {
  const elapsed = state.tick - state.cycleStartTick;
  const actions = [];
  if (elapsed === (preferRightFirst ? 30 : 5)) actions.push('left-press');
  if (elapsed === (preferRightFirst ? 3 : 12)) actions.push('right-press');
  if (elapsed < 12) return actions;
  if (!state.leftHeld && elapsed > 30) return actions;
  if (!state.rightHeld && state.pressure < 56) actions.push('right-press');
  if (state.rightHeld && state.pressure > 73) actions.push('right-release');
  return actions;
}

const success = recordRun(
  (engine, state) => safePulse(engine, state, state.completed === 0),
  {
    id: 'demo-synchronized',
    title: '示范：三组同步 + 备件保留',
    summary: '第一组右侧提前 432ms 启动，时间线记录顺序冲突；三组仍全部锁定。'
  }
);

const failure = recordRun(
  (engine, state) => {
    const elapsed = state.tick - state.cycleStartTick;
    const actions = [];
    if (elapsed === 5) actions.push('left-press');
    if (elapsed === 12) actions.push('right-press');
    return actions;
  },
  {
    id: 'demo-pressure-failure',
    title: '失败：右侧持续加压',
    summary: '压力越过 92%，垫圈压溃；碰撞时刻和垫圈坐标被写入时间线。'
  }
);

const source = `// Generated by scripts/generate-demo.mjs. Do not edit by hand.\n`
  + `export const DEMO_REPLAY = ${JSON.stringify(success, null, 2)};\n\n`
  + `export const FAILURE_REPLAY = ${JSON.stringify(failure, null, 2)};\n`;

await writeFile(new URL('../src/demo-replay.js', import.meta.url), source, 'utf8');
console.log(JSON.stringify({
  success: success.expected,
  successConflicts: success.recordedTimeline.conflicts.length,
  failure: failure.expected,
  failureCollisions: failure.recordedTimeline.collisions.length
}, null, 2));
